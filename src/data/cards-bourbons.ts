import type { Card, Source } from './schema.ts'

function primary(author: string, work: string, locus?: string): Source {
  return locus === undefined ? { kind: 'primary', author, work } : { kind: 'primary', author, work, locus }
}

function modern(author: string, work: string): Source {
  return { kind: 'modern', author, work }
}

